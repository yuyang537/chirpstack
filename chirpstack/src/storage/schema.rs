/*
 * 模块概述
 * ========
 * 数据库模式模块是ChirpStack存储层的基础组件，负责定义数据库表结构和关系。该模块通过
 * 条件编译特性(feature flags)提供了对不同数据库后端（PostgreSQL和SQLite）的支持，
 * 使ChirpStack能够在不同的部署环境中灵活选择适合的数据库系统。
 * 
 * 该模块采用了Diesel ORM的模式定义方式，将数据库表结构以Rust代码的形式表示，实现了
 * 类型安全的数据库访问。通过这种方式，编译器可以在编译时捕获许多潜在的数据库查询错误，
 * 提高了代码的健壮性。
 *
 * 文件功能
 * ========
 * 本文件(schema.rs)是数据库模式定义的入口点，提供了以下主要功能：
 * 1. 根据编译特性选择适当的数据库模式定义
 * 2. 重新导出特定数据库后端的模式定义
 *
 * 主要组件
 * ========
 * - 条件导入: 根据编译特性(postgres或sqlite)导入相应的模式定义
 *
 * 关键流程
 * ========
 * 1. 模式选择流程:
 *    - 在编译时根据特性标志选择数据库后端
 *    - 导入相应的模式定义
 *    - 将模式定义重新导出，供存储模块的其他部分使用
 *
 * 注意事项
 * ========
 * - 数据库兼容性: 确保两种数据库后端的模式定义保持兼容
 * - 模式演进: 数据库模式的变更需要通过迁移脚本实现，确保向后兼容
 * - 条件编译: 使用特性标志控制编译，避免不必要的依赖
 * - 类型安全: 利用Diesel ORM提供的类型安全特性，减少运行时错误
 * - 代码组织: 将具体的模式定义放在单独的文件中，保持代码的清晰和可维护性
 */

