/*
 * 模块概述
 * ========
 * 下行链路错误(Error)模块是ChirpStack LoRaWAN网络服务器下行链路处理框架的错误处理组件，
 * 负责定义和管理下行链路处理过程中可能遇到的各种错误类型。在复杂的LoRaWAN下行链路处理流程中，
 * 错误处理是确保系统稳定性和可靠性的关键部分。
 * 
 * 该模块与下行链路处理的其他组件紧密集成，为整个下行链路框架提供了统一的错误处理机制。
 * 它定义了特定于下行链路处理的错误类型，同时也集成了来自其他模块（如存储层）的错误，
 * 使得错误能够在不同层次之间正确传播和处理。
 * 
 * 在LoRaWAN网络服务器中，下行链路错误处理对于诊断问题、记录日志和实现错误恢复策略至关重要，
 * 特别是在处理大量设备和网关的生产环境中。
 *
 * 文件功能
 * ========
 * 本文件(error.rs)定义了下行链路处理中使用的错误类型，提供了以下主要功能：
 * 1. 定义下行链路特定的错误枚举类型
 * 2. 实现错误类型之间的转换（通过From trait）
 * 3. 提供错误的字符串表示（通过Display trait）
 * 4. 集成来自其他模块的错误类型
 *
 * 主要组件
 * ========
 * - Error: 核心错误枚举，包含以下变体：
 *   - Abort: 表示处理应该中止，但不是因为错误（例如，没有更多需要处理的数据）
 *   - Anyhow: 包装通用错误类型，用于集成来自各种来源的错误
 *   - Storage: 包装存储层错误，用于处理数据库和缓存相关的错误
 *
 * 关键流程
 * ========
 * 1. 错误生成流程:
 *    - 在下行链路处理的各个阶段，当遇到异常情况时，创建相应的错误类型
 *    - 使用thiserror宏自动实现错误特性，提供详细的错误信息
 *    - 通过From实现，允许不同错误类型之间的自动转换
 *
 * 2. 错误处理流程:
 *    - 调用代码通过模式匹配或错误传播操作符(?)处理错误
 *    - 根据错误类型执行不同的恢复策略或日志记录
 *    - 特殊处理Abort错误，它表示正常的流程终止而非实际错误
 *
 * 注意事项
 * ========
 * - 错误区分: 需要明确区分实际错误和正常的流程控制（如Abort）
 * - 错误上下文: 错误信息应提供足够的上下文，便于诊断和解决问题
 * - 错误传播: 确保错误能够正确地从底层组件传播到上层处理逻辑
 * - 错误恢复: 某些错误可能允许重试或恢复，而其他错误可能需要中止整个操作
 * - 日志记录: 关键错误应该被适当记录，以便后续分析和监控
 */

use thiserror::Error;

#[derive(Error, Debug)]
pub enum Error {
    #[error("Nothing else to do")]
    Abort,

    #[error(transparent)]
    Anyhow(#[from] anyhow::Error),

    #[error(transparent)]
    Storage(#[from] crate::storage::error::Error),
}
